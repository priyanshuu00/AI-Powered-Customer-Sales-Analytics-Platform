import os
import logging
from .eda import DataProfiler
from .sales_analysis import SalesAnalyzer
from .customer_analysis import CustomerAnalyzer
from .product_analysis import ProductAnalyzer
from .payment_analysis import PaymentAnalyzer
from .review_analysis import ReviewAnalyzer
from .statistics import StatAnalyzer

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

REPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "reports")

def generate_report():
    logger.info("Starting Data Analysis and Report Generation...")
    
    profiler = DataProfiler()
    
    sales_insights = SalesAnalyzer(profiler).analyze()
    customer_insights = CustomerAnalyzer(profiler).analyze()
    product_insights = ProductAnalyzer(profiler).analyze()
    payment_insights = PaymentAnalyzer(profiler).analyze()
    review_insights = ReviewAnalyzer(profiler).analyze()
    
    # Generate business insights strings automatically
    business_insights = []
    
    if sales_insights:
        business_insights.append(f"The highest revenue month was {sales_insights.get('top_revenue_month')} with ${sales_insights.get('top_month_revenue', 0):,.2f}.")
        
    if customer_insights:
        business_insights.append(f"Repeat customers contribute {customer_insights.get('repeat_customer_revenue_contribution', 0):.1f}% of total revenue despite being {customer_insights.get('repeat_customer_rate', 0):.1f}% of the user base.")
        
    if product_insights:
        business_insights.append(f"'{product_insights.get('top_category')}' is the top-performing category, generating the highest sales volume.")
        
    if payment_insights:
        business_insights.append(f"{payment_insights.get('dominant_payment_type').capitalize()} is used in {payment_insights.get('dominant_payment_percentage', 0):.0f}% of transactions.")
        
    if review_insights:
        business_insights.append(f"Overall average satisfaction score is {review_insights.get('average_rating', 0):.2f}/5, with {review_insights.get('positive_reviews_pct', 0):.1f}% positive reviews.")

    # Write Markdown Report
    report_content = f"""# Business Analytics & EDA Report

## Executive Summary
This report presents an exploratory data analysis of the Olist E-Commerce dataset. It covers sales trends, customer behavior, product performance, and payment distributions.

## Key KPIs
- **Total Customers**: {customer_insights.get('total_customers', 0):,}
- **Average Customer Lifetime Value**: ${customer_insights.get('average_clv', 0):,.2f}
- **Average Order Rating**: {review_insights.get('average_rating', 0):.2f} / 5.0
- **Average Payment Value**: ${payment_insights.get('average_payment_value', 0):,.2f}

## Business Insights
"""
    for insight in business_insights:
        report_content += f"- {insight}\n"

    report_content += """
## Recommendations
1. **Target Repeat Customers**: Given the disproportionate revenue generated by returning users, implementing a loyalty program could drastically boost MRR.
2. **Category Expansion**: Expand inventory and marketing efforts around the top-performing categories.
3. **Payment Optimization**: Ensure seamless experiences for the dominant payment type, and perhaps offer incentives for installment-based payments to increase Average Order Value (AOV).

## Visualizations
Charts have been generated and saved in the `reports/charts/` directory.

## Conclusion
The data highlights a highly active e-commerce ecosystem with clear seasonal peaks and dominant product categories. Focusing on post-purchase retention and logistics optimization (to maintain high review scores) are the strongest pathways to growth.
"""

    report_path = os.path.join(REPORTS_DIR, "business_analysis_report.md")
    with open(report_path, "w") as f:
        f.write(report_content)
        
    logger.info(f"Analytics report successfully generated at {report_path}")

if __name__ == "__main__":
    generate_report()
