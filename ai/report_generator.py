import os
from .gemini_client import GeminiClient
from .executive_summary import ExecutiveSummaryGenerator
from .insight_generator import InsightGenerator
from .recommendation_engine import RecommendationEngine
from .ai_logger import setup_logger
from .prompt_builder import PromptBuilder

logger = setup_logger("ReportGenerator")
REPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "reports")

class ChatInterface:
    def __init__(self, client: GeminiClient, context: dict):
        self.client = client
        self.context = context

    def ask(self, question: str) -> str:
        prompt = PromptBuilder.build_chat_prompt(question, self.context)
        return self.client.generate_response(prompt) or "I'm sorry, I could not process that request."

class AIReportGenerator:
    def __init__(self):
        self.client = GeminiClient()
        self.exec_summary_gen = ExecutiveSummaryGenerator(self.client)
        self.insight_gen = InsightGenerator(self.client)
        self.rec_gen = RecommendationEngine(self.client)

    def generate_full_report(self, kpis: dict, sales_data: dict, customer_data: dict):
        logger.info("Starting full AI Business Report generation...")
        
        summary = self.exec_summary_gen.generate(kpis)
        sales_insights = self.insight_gen.generate("Sales", sales_data)
        customer_insights = self.insight_gen.generate("Customers", customer_data)
        
        combined_insights = f"Sales Insights:\n{sales_insights}\n\nCustomer Insights:\n{customer_insights}"
        recommendations = self.rec_gen.generate(combined_insights)
        
        report_content = f"""# AI Business Intelligence Report

## Executive Summary
{summary}

## Business Insights & Root Cause Analysis
{combined_insights}

## Recommendations
{recommendations}

## Conclusion
This report was automatically generated by the AI Business Intelligence Engine. Please review the recommendations and consult with departmental heads before taking strategic action.
"""
        os.makedirs(REPORTS_DIR, exist_ok=True)
        report_path = os.path.join(REPORTS_DIR, "ai_business_report.md")
        
        with open(report_path, "w") as f:
            f.write(report_content)
            
        logger.info(f"Report generated successfully at {report_path}")

# Example usage entrypoint
if __name__ == "__main__":
    # Mock data for demonstration purposes. In a real scenario, this would be fetched via SQL/Pandas.
    mock_kpis = {"total_revenue": 15000000, "total_orders": 99000, "average_delivery_time": 12.5}
    mock_sales = {"Q1_revenue": 3000000, "Q2_revenue": 2800000, "notes": "Slight dip in Q2"}
    mock_customers = {"total": 95000, "repeat_rate": "15%"}
    
    generator = AIReportGenerator()
    try:
        generator.generate_full_report(mock_kpis, mock_sales, mock_customers)
    except Exception as e:
        logger.error(f"Process failed: {e}")
